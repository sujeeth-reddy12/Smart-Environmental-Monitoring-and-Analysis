export function getCityDetails(city) {
  const normalized = (city || 'Hyderabad').trim()
  const foundKey = Object.keys(CITY_DATA_MAP).find(
    (k) => k.toLowerCase() === normalized.toLowerCase()
  )
  if (foundKey) {
    return { name: foundKey, ...CITY_DATA_MAP[foundKey] }
  }

  // Hash-based deterministic fallback for any unknown city string
  let hash = 0
  for (let i = 0; i < normalized.length; i++) {
    hash = normalized.charCodeAt(i) + ((hash << 5) - hash)
  }
  const posHash = Math.abs(hash)
  const dynamicAqi = 45 + (posHash % 120)
  const dynamicTemp = 24 + ((posHash % 140) / 10)
  const dynamicHumidity = 40 + (posHash % 45)

  return {
    name: normalized,
    state: 'India',
    lat: Number((15 + (posHash % 15) + (posHash % 100) / 100).toFixed(4)),
    lon: Number((72 + (posHash % 15) + (posHash % 100) / 100).toFixed(4)),
    aqi: dynamicAqi,
    pm25: Number((dynamicAqi * 0.35).toFixed(2)),
    pm10: Number((dynamicAqi * 0.65).toFixed(2)),
    co: Number((100 + (posHash % 150)).toFixed(2)),
    no: Number((5 + (posHash % 20)).toFixed(2)),
    no2: Number((20 + (posHash % 35)).toFixed(2)),
    so2: Number((3 + (posHash % 10)).toFixed(2)),
    o3: Number((25 + (posHash % 30)).toFixed(2)),
    co2: 500 + (posHash % 250),
    temp: Number(dynamicTemp.toFixed(1)),
    humidity: dynamicHumidity,
    pressure: 1008 + (posHash % 8),
    wind: Number((2 + (posHash % 40) / 10).toFixed(2)),
    visibility: Number((6 + (posHash % 40) / 10).toFixed(1)),
    rain: 0,
    score: Math.max(30, Math.min(95, 100 - Math.round(dynamicAqi * 0.4))),
    status: dynamicAqi <= 50 ? 'Good' : dynamicAqi <= 100 ? 'Moderate' : 'Poor',
  }
}

export function findClosestCity(lat, lon) {
  let closest = 'Hyderabad'
  let minDistance = Infinity

  for (const [cityName, data] of Object.entries(CITY_DATA_MAP)) {
    const dLat = data.lat - lat
    const dLon = data.lon - lon
    const dist = dLat * dLat + dLon * dLon
    if (dist < minDistance) {
      minDistance = dist
      closest = cityName
    }
  }
  return closest
}
